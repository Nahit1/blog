function kind(url: string) {
  const host = (() => {
    try {
      return new URL(url).hostname.replace(/^www\./, "");
    } catch {
      return "";
    }
  })();
  if (host.endsWith("github.com")) return "github";
  if (host.endsWith("linkedin.com")) return "linkedin";
  if (host === "x.com" || host.endsWith("twitter.com")) return "x";
  if (host.endsWith("instagram.com")) return "instagram";
  if (host.endsWith("youtube.com") || host === "youtu.be") return "youtube";
  if (host.endsWith("medium.com")) return "medium";
  return null;
}

/** Link adresine göre marka ikonu; tanınmayan siteler için küre ikonu. */
export function SocialIcon({ url, className = "size-5" }: { url: string; className?: string }) {
  const k = kind(url);
  return (
    <svg viewBox="0 0 24 24" className={className} fill="currentColor" aria-hidden>
      <path d={k ? PATHS[k] : GLOBE} />
    </svg>
  );
}

export function SocialLinks({ links, className = "" }: { links: { label: string; url: string }[]; className?: string }) {
  if (links.length === 0) return null;
  return (
    <ul className={`flex flex-wrap items-center gap-2 ${className}`}>
      {links.map((l) => (
        <li key={l.url}>
          <a
            href={l.url}
            target="_blank"
            rel="noopener noreferrer"
            title={l.label}
            aria-label={l.label}
            className="grid size-10 place-items-center rounded-full border border-line bg-surface text-muted transition hover:-translate-y-0.5 hover:border-accent hover:text-accent"
          >
            <SocialIcon url={l.url} />
          </a>
        </li>
      ))}
    </ul>
  );
}
